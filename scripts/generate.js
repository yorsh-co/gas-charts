import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const SCRIPT_CLOSE = /<\/(script)/gi;
const HTML_COMMENT_OPEN = /<!--/g;

/**
 * Makes JS source safe to embed in an inline `<script>` element. The
 * replacements are value-preserving only inside string, untagged template and
 * non-unicode (no `u`/`v` flag) regex literals. They would change
 * `String.raw`/tagged templates and break code outside literals (e.g.
 * `a<!--b`), so callers should check {@link countInlineScriptEscapes}.
 * @param {string} code
 * @returns {string}
 */
export function escapeInlineScript(code) {
  return code
    .replace(SCRIPT_CLOSE, '<\\/$1')
    .replace(HTML_COMMENT_OPEN, '<\\!--');
}

/**
 * Counts the sequences {@link escapeInlineScript} would rewrite.
 * @param {string} code
 * @returns {number}
 */
export function countInlineScriptEscapes(code) {
  return (
    (code.match(SCRIPT_CLOSE)?.length ?? 0) +
    (code.match(HTML_COMMENT_OPEN)?.length ?? 0)
  );
}

/**
 * Renders a TypeScript module of string constants.
 * @param {{ source: string, declarations: Record<string, string> }} options
 *   `source` is a human-readable origin note; `declarations` maps constant
 *   names to their string values.
 * @returns {string}
 */
export function toModule({ source, declarations }) {
  const lines = [`// Generated by ${source}. Do not edit.`];
  for (const [name, value] of Object.entries(declarations)) {
    const literal = JSON.stringify(value)
      .replace(/\u2028/g, '\\u2028')
      .replace(/\u2029/g, '\\u2029');
    lines.push('// prettier-ignore', `const ${name}: string = ${literal};`);
  }
  return lines.join('\n') + '\n';
}

/**
 * Computes every generated file.
 * @param {string} root Repository root.
 * @returns {{ path: string, content: string }[]}
 */
export function generate(root) {
  const dist = join(root, 'node_modules/echarts');
  const js = readFileSync(join(dist, 'dist/echarts.min.js'), 'utf8');
  const { version } = JSON.parse(
    readFileSync(join(dist, 'package.json'), 'utf8'),
  );
  const escapes = countInlineScriptEscapes(js);
  if (escapes > 0) {
    console.error(
      `warning: ${escapes} inline-script escape(s) applied in node_modules/echarts/dist/echarts.min.js; review manually`,
    );
  }
  const client = ts.transpileModule(
    readFileSync(join(root, 'src/web/gas-charts.client.ts'), 'utf8'),
    {
      compilerOptions: {
        target: ts.ScriptTarget.ES2020,
        module: ts.ModuleKind.None,
      },
    },
  ).outputText;
  const clientEscapes = countInlineScriptEscapes(client);
  if (clientEscapes > 0) {
    console.error(
      `warning: ${clientEscapes} inline-script escape(s) applied in src/web/gas-charts.client.ts; review manually`,
    );
  }
  return [
    {
      path: join(root, 'src/generated/gas-charts.echarts.ts'),
      content: toModule({
        source: 'scripts/generate.js from node_modules/echarts',
        declarations: {
          _GAS_CHARTS_ECHARTS_JS: escapeInlineScript(js),
          GAS_CHARTS_ECHARTS_VERSION: version,
        },
      }),
    },
    {
      path: join(root, 'src/generated/gas-charts.client.ts'),
      content: toModule({
        source: 'scripts/generate.js from src/web/gas-charts.client.ts',
        declarations: { _GAS_CHARTS_CLIENT_JS: escapeInlineScript(client) },
      }),
    },
  ];
}

/** CLI entry: writes outputs, or with `--check` exits 1 naming stale files. */
function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const outputs = generate(root);
  if (process.argv.includes('--check')) {
    const stale = outputs.filter(
      ({ path, content }) =>
        !existsSync(path) || readFileSync(path, 'utf8') !== content,
    );
    if (stale.length > 0) {
      console.error(
        `Stale generated files (run npm run generate):\n${stale
          .map(({ path }) => relative(root, path))
          .join('\n')}`,
      );
      process.exit(1);
    }
    return;
  }
  for (const { path, content } of outputs) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
