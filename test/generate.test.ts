import { spawnSync } from 'node:child_process';
import { relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import {
  countInlineScriptEscapes,
  escapeInlineScript,
  generate,
  toModule,
  // @ts-expect-error plain JS module without declarations
} from '../scripts/generate.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

describe('escapeInlineScript', () => {
  it('escapes closing script tags case-insensitively', () => {
    expect(escapeInlineScript('a</script>b</SCRIPT >')).toBe(
      'a<\\/script>b<\\/SCRIPT >',
    );
  });

  it('escapes HTML comment openers', () => {
    expect(escapeInlineScript('x<!--y')).toBe('x<\\!--y');
  });

  it('counts the sequences it rewrites', () => {
    expect(countInlineScriptEscapes('</script></SCRIPT><!--')).toBe(3);
    expect(countInlineScriptEscapes('var a = 1;')).toBe(0);
  });

  it('leaves other code untouched', () => {
    expect(escapeInlineScript('var a = "$&" < 1;')).toBe('var a = "$&" < 1;');
  });
});

describe('toModule', () => {
  const value = 'line\n"q"   $& </x>';
  const out: string = toModule({ source: 'test', declarations: { A: value } });

  it('emits a header and prettier-ignore', () => {
    expect(out.startsWith('// Generated by test. Do not edit.\n')).toBe(true);
    expect(out).toContain('// prettier-ignore\nconst A: string = ');
  });

  it('round-trips the value through JSON.parse', () => {
    const literal = /const A: string = (.*);\n$/.exec(out)![1]!;
    expect(JSON.parse(literal)).toBe(value);
  });

  it('escapes U+2028 and U+2029', () => {
    expect(out).not.toMatch(/[\u2028\u2029]/);
    expect(out).toContain('\\u2028');
    expect(out).toContain('\\u2029');
  });
});

describe('generate', () => {
  it('emits exactly the ECharts and client modules', () => {
    const paths = (generate(ROOT) as { path: string }[]).map(({ path }) =>
      relative(ROOT, path),
    );
    expect(paths).toEqual([
      'src/generated/gas-charts.echarts.ts',
      'src/generated/gas-charts.client.ts',
    ]);
  });

  it('transpiles the client to plain script JS', () => {
    const client = (generate(ROOT) as { path: string; content: string }[]).find(
      ({ path }) => path.endsWith('gas-charts.client.ts'),
    )!.content;
    expect(client).toContain('_GAS_CHARTS_CLIENT_JS');
    expect(client).not.toMatch(/\bexport\b|\bimport\b/);
    expect(client).not.toContain('GasChartsClient');
  });

  it('passes `generate.js --check`', () => {
    const result = spawnSync('node', ['scripts/generate.js', '--check'], {
      cwd: ROOT,
    });
    expect(result.status).toBe(0);
  });

  it('matches the committed files', () => {
    for (const { path, content } of generate(ROOT) as {
      path: string;
      content: string;
    }[]) {
      expect(readFileSync(path, 'utf8')).toBe(content);
    }
  });
});
